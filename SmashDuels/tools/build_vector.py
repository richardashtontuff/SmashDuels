#!/usr/bin/env python3
"""Slice Vector's curated source poses into an anchored atlas (Pillow/NumPy/SciPy).

The gray source sheet has no dedicated idle or hang row: idle reuses the neutral
slash stance and the separately generated ledge pose is built by the ledge tool.
Baked missile barrages and overlapping or clipped poses are deliberately omitted;
missiles are generated by gameplay, not pasted onto the character.
"""
from PIL import Image
import numpy as np
from scipy import ndimage
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/"game/assets"
src=Image.open(ROOT/'assets-src/characters/vector-sheets/Vector-01.png').convert('RGB')
# x limits y limits and anchor relative source, ground y
C={'idle':(5,585,180,727,92,725),'r1':(8,50,156,220,86,219),'r2':(165,50,330,220,252,219),'r3':(335,50,505,220,421,219),'r4':(507,50,661,220,590,219),'r5':(688,50,854,220,774,219),'r6':(1040,50,1197,220,1122,219),'r7':(1178,50,1358,220,1288,219),'r8':(1362,50,1518,220,1441,219),'j1':(4,325,125,471,66,469),'j2':(133,294,251,471,191,469),'j3':(258,290,364,470,313,469),'j4':(375,297,485,470,430,469),'j5':(482,328,621,471,551,469),'j6':(622,350,750,471,686,469),'d1':(748,325,889,471,831,469),'d2':(908,325,1041,471,975,469),'d6':(1385,318,1526,471,1455,469),'s1':(5,585,180,727,92,725),'s2':(212,565,407,727,309,725),'s4':(742,560,1008,727,862,725),'s6':(1275,568,1525,727,1415,725),'g1':(10,795,208,982,110,980),'g2':(226,808,465,982,334,980),'g6':(1306,818,1520,982,1414,980)}
def cut(box):
 x0,y0,x1,y1,ax,ay=box; rgb=np.array(src.crop((x0,y0,x1,y1))).astype(np.int16)
 # flat grey background: retain foreground and anti-aliased boundary pixels
 diff=np.max(np.abs(rgb-130),axis=2); mask=diff>21
 # Largest connected silhouette; keeps appendages + connected effects, excludes neighbouring poses and printed shadows.
 lab,n=ndimage.label(mask);sizes=np.bincount(lab.ravel());sizes[0]=0; main=lab==np.argmax(sizes)
 # Restore small enclosed armor highlights, not the large open background gaps
 # (the source's floor stroke can enclose the space between the legs).
 holes=ndimage.binary_fill_holes(main) & ~main
 hl,hn=ndimage.label(holes); hs=np.bincount(hl.ravel()); hs[0]=0
 main |= (hl>0) & (hs[hl] <= 100)
 keep=ndimage.binary_dilation(main,iterations=2)
 alpha=np.clip((diff-7)/19,0,1)*keep
 # retain interior dark gray highlights while leaving the backdrop transparent
 alpha=np.where(main,1,alpha)
 # Thin painted ground shadows must not be carried into airborne animations.
 for row in range(max(0, alpha.shape[0]-8), alpha.shape[0]):
  line,nline=ndimage.label(alpha[row]>.25); sizes=np.bincount(line); sizes[0]=0
  alpha[row][sizes[line]>40]=0
 rgba=np.dstack((rgb.astype('uint8'),(alpha*255).astype('uint8')));im=Image.fromarray(rgba,'RGBA');bb=im.getchannel('A').getbbox();im=im.crop(bb);return im,(ax-x0-bb[0],ay-y0-bb[1])
# Deliberately omit damaged/overlapping tiles and baked missile swarms; missiles
# are simulated projectiles, never painted on the fighter's body.
I='idle'; R=['r1','r2','r3','r6','r7','r8']; J=['j1','j2','j3','j4','j5','j6']; D=['d1','r2','d6'];
A={
 'idle':[I], 'walk':R,'run':R,'dash':R[:3], 'jump':J[:4], 'fall':[J[3],J[0]],'land':[J[5],J[4],I], 'crouch':[J[5]], 'turn':[J[4]],
 'jab':[I,'low','punch','low',I], 'stilt':[I,'low','punch','low',I], 'utilt':[I,'low','upper','low',I], 'dtilt':[J[5],I,'low',J[5],I],
 'ssmash':[I,'low','punch','low',I], 'usmash':[I,'low','upper','low',I], 'dsmash':[J[5],I,'low',J[5],I], 'dashattack':[I,D[0],'punch',D[2],I],
 'nair':[J[3],J[1],'punch',J[3]],'fair':[J[3],J[1],'punch',J[3]],'bair':[J[3],J[1],'punch',J[3]],'uair':[J[3],J[1],'upper',J[3]],'dair':[J[3],J[1],'low',J[3]],
 'nspecial':[I,'g1','g2',I], 'sspecial':[D[0],D[0],D[1],D[2],I], 'uspecial':[J[1],J[3],J[1],J[2],J[3],J[1]], 'dspecial':[I,'g1','g2',I],
 'shield':[I],'shieldbreak':[J[3]],'hurt':[J[3]],'launch':[J[3]],'grab':[I,'g2'],'grabbed':[J[3]],'rollfwd':[J[5],J[0],J[5]],'rollback':[J[5],J[0],J[5]],'spotdodge':[J[5],I],'airdodge':[J[0],J[3]],'down':[J[5]],'getup':[J[5],J[4],I],'respawn':[J[3],I],'ko':[J[3]],'taunt1':[I,'g1','g2',I],'taunt2':[I,'s2','s4',I],'taunt3':[I,'g1','g2',I]}
TIMING={n:{'strike':2,'wind':1} for n in ['jab','stilt','utilt','dtilt','ssmash','usmash','dsmash','dashattack','nair','fair','bair','uair','dair','nspecial']}
TIMING.update({n:{'fit':True} for n in ['sspecial','uspecial','dspecial']})
def generated_pose(name):
 # Chroma-key the individually authored strike, retaining antialiased edges.
 rgb=np.array(Image.open(ROOT/'assets-src/characters/vector-sheets'/('f-'+name+'.png')).convert('RGB')).astype(np.float32)
 green=rgb[:,:,1]-np.maximum(rgb[:,:,0],rgb[:,:,2])
 alpha=np.clip((75-green)/65,0,1)
 rgba=np.dstack((rgb.astype('uint8'),(alpha*255).astype('uint8')))
 im=Image.fromarray(rgba,'RGBA'); bb=im.getchannel('A').getbbox(); im=im.crop(bb)
 # Same head and torso scale as the sheet's idle (not the source canvas size).
 factor=137/im.height
 im=im.resize((round(im.width*factor),137),Image.Resampling.LANCZOS)
 return im, ((550-bb[0])*factor,(950-bb[1])*factor)

def main():
 names=sorted({k for row in A.values() for k in row}); images=[]; frames={}; tiles=[]; sources=[]
 folder=OUT/'frames/vector';folder.mkdir(parents=True,exist_ok=True)
 for stale in folder.glob('*.png'):
  if stale.stem not in names: stale.unlink()
 for k in names:
  if k in ('punch','upper','low'):
   img,(ax,ay)=generated_pose({'punch':'punch','upper':'up','low':'low'}[k]); factor=1
  else:
   img,(ax,ay)=cut(C[k]); # The airborne drawings on the supplied sheet are individually smaller
   # than the idle artwork. Match their helmets/torso to idle, not their total
   # height: tucked knees and straight legs naturally have different bounds.
   factor={'j1':1.12,'j2':1.15,'j3':1.16,'j4':1.12,'j5':1.08,'j6':1.12}.get(k,.9 if k[0]=='r' else 1)
  if factor!=1:
   img=img.resize((round(img.width*factor),round(img.height*factor)),Image.Resampling.LANCZOS);ax*=factor;ay*=factor
  idx=len(images);images.append(img);frames[k]=[idx,round(ax,2),round(ay,2),[]];img.save(folder/(k+'.png'))
  sources.append({'file':k+'.png','tile':idx,'source':('f-'+{'punch':'punch','upper':'up','low':'low'}[k]+'.png') if k in ('punch','upper','low') else 'Vector-01.png'})
 x=y=2;shelf=0;aw=1024
 for img in images:
  if x+img.width+2>aw: x=2;y+=shelf+2;shelf=0
  tiles.append({'x':x,'y':y,'w':img.width,'h':img.height});x+=img.width+2;shelf=max(shelf,img.height)
 atlas=Image.new('RGBA',(aw,y+shelf+2))
 for t,img in zip(tiles,images):atlas.paste(img,(t['x'],t['y']))
 atlas.save(OUT/'atlas/vector.png',optimize=True);images[names.index(I)].save(OUT/'portraits/vector_base.png')
 (OUT/'atlas/vector.json').write_text(json.dumps({'refH':150,'tiles':tiles,'anims':{n:[frames[k] for k in row] for n,row in A.items()},'actionTiming':TIMING,'sourceFrames':sources},separators=(',',':')))
 print('Vector',len(images),'frames',atlas.size)
if __name__=='__main__':main()
